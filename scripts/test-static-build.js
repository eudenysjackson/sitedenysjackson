const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { render, element } = require('./build-static');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const data = Object.fromEntries(['about', 'gallery', 'shows', 'tribute', 'videos', 'site', 'social_proof'].map(name => [name, JSON.parse(fs.readFileSync(path.join(root, 'content', name + '.json'), 'utf8'))]));
const html = render(source, data);
const inner = (text, id) => { const e = element(text, id); return text.slice(e.inner, e.end); };
assert(!html.includes('Foto será carregada do painel'));
assert.equal((inner(html, 'gallery-grid').match(/class="gallery-item"/g) || []).length, data.gallery.photos.length);
if (data.about.main_photo) assert(inner(html, 'about-photo').includes('<img'));
assert(inner(html, 'about-bio').includes(data.about.bio_pt.split('\n')[0].slice(0, 40)));
if (data.gallery.photos.length) assert(!html.includes('Fotos serão adicionadas em breve'));
const withShow = structuredClone(data);
withShow.shows.shows = [{ date: '2099-11-14', venue: 'Teatro de teste', city: 'Rio de Janeiro', status: 'confirmado' }];
const showHtml = render(source, withShow);
assert(inner(showHtml, 'shows-list').includes('Teatro de teste'));
assert(!showHtml.includes('Em breve novos shows serão anunciados'));
assert(!html.includes('class="fade-in'));
const empty = structuredClone(data);
empty.gallery.photos = []; empty.shows.shows = []; empty.videos.videos = [];
const emptyHtml = render(source, empty);
assert(inner(emptyHtml, 'gallery-empty').includes('Fotos serão adicionadas'));
assert(inner(emptyHtml, 'shows-empty').includes('Em breve novos shows'));
assert.equal(inner(emptyHtml, 'gallery-grid'), '');
const edited = structuredClone(data);
edited.about.bio_pt = '<script>alert("x")</script> & biografia nova';
edited.gallery.photos = [{ image: '/images/test.jpg', caption: 'Foto de teste' }];
const updated = render(source, edited);
assert(inner(updated, 'about-bio').includes('&lt;script&gt;'));
assert.equal((inner(updated, 'gallery-grid').match(/class="gallery-item"/g) || []).length, 1);
assert.equal(render(html, data), html, 'Generation must be repeatable');
console.log('OK: HTML without JS contains CMS content; empty states, escaping, edits and repeatability verified.');
